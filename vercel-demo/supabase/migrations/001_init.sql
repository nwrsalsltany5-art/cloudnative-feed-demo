create or replace function public.check_rate_limit(
    p_visitor_key text,
    p_action text,
    p_limit integer,
    p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    this_window timestamptz;
    current_count integer;
begin
    if char_length(p_visitor_key) not between 1 and 128
       or p_action not in ('photo_like', 'comment_like', 'comment', 'demo_simulation')
       or p_limit < 1 or p_window_seconds not between 1 and 3600 then
        raise exception 'invalid rate limit request' using errcode = '22023';
    end if;
    this_window := to_timestamp(
        floor(extract(epoch from now()) / p_window_seconds) * p_window_seconds
    );
    insert into public.request_rate_limits (visitor_key, action, window_start, request_count)
    values (p_visitor_key, p_action, this_window, 1)
    on conflict (visitor_key, action, window_start)
    do update set request_count = public.request_rate_limits.request_count + 1
    returning request_count into current_count;
    delete from public.request_rate_limits
    where window_start < now() - interval '1 day';
    return current_count <= p_limit;
end;
$$;

create or replace function public.record_app_request(
    p_status integer,
    p_duration_ms bigint,
    p_activity text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    bucket timestamptz := date_trunc('minute', now());
begin
    if p_status not between 100 and 599 or p_duration_ms < 0
       or p_activity not in ('', 'comment', 'photo_like', 'comment_like') then
        raise exception 'invalid application measurement' using errcode = '22023';
    end if;
    insert into public.usage_minutes (
        bucket_start, request_count, error_count, total_latency_ms,
        comment_count, photo_like_count, comment_like_count
    )
    values (
        bucket, 1, case when p_status >= 500 then 1 else 0 end, p_duration_ms,
        case when p_activity = 'comment' then 1 else 0 end,
        case when p_activity = 'photo_like' then 1 else 0 end,
        case when p_activity = 'comment_like' then 1 else 0 end
    )
    on conflict (bucket_start) do update set
        request_count = public.usage_minutes.request_count + 1,
        error_count = public.usage_minutes.error_count + excluded.error_count,
        total_latency_ms = public.usage_minutes.total_latency_ms + excluded.total_latency_ms,
        comment_count = public.usage_minutes.comment_count + excluded.comment_count,
        photo_like_count = public.usage_minutes.photo_like_count + excluded.photo_like_count,
        comment_like_count = public.usage_minutes.comment_like_count + excluded.comment_like_count;
    delete from public.usage_minutes
    where bucket_start < now() - interval '7 days';
end;
$$;

create or replace function public.run_demo_simulation(p_actor_username text)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    run_id bigint;
    now_at timestamptz := clock_timestamp();
begin
    if not exists (
        select 1 from public.admin_access
        where username = p_actor_username and enabled
          and (role = 'owner' or (role = 'admin' and can_load_test))
    ) then
        raise exception 'simulation permission required' using errcode = '42501';
    end if;
    perform pg_advisory_xact_lock(hashtext('vercel-feed-demo-simulation'));
    delete from public.demo_load_runs
    where started_at < now_at - interval '30 days';
    if exists (
        select 1 from public.demo_load_runs
        where started_at > now_at - interval '120 seconds'
    ) then
        raise exception 'cooldown' using errcode = 'P0001';
    end if;
    insert into public.demo_load_runs (
        actor_username, started_at, finished_at, duration_ms, simulated_vus, result
    )
    values (
        p_actor_username, now_at, now_at + interval '90 seconds', 90000, 10,
        'simulated; no external load generated'
    )
    returning id into run_id;
    return (
        select to_jsonb(run)
        from public.demo_load_runs run
        where run.id = run_id
    );
end;
$$;

