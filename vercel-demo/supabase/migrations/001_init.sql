create or replace function public.get_feed(p_visitor_key text)
returns table (
    id integer,
    title text,
    image_url text,
    likes_count integer,
    comments_count bigint,
    liked boolean
)
language sql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
    select p.id, p.title, p.image_url, p.likes_count, count(c.id),
           exists (
               select 1 from public.photo_likes pl
               where pl.photo_id = p.id and pl.visitor_key = p_visitor_key
           )
    from public.photos p
    left join public.comments c on c.photo_id = p.id
    group by p.id
    order by p.id
$$;

create or replace function public.get_comments(p_photo_id integer, p_visitor_key text)
returns table (
    id integer,
    author text,
    message text,
    likes_count integer,
    created_at timestamptz,
    liked boolean
)
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
begin
    if not exists (select 1 from public.photos where id = p_photo_id) then
        raise exception 'photo not found' using errcode = 'P0002';
    end if;
    return query
        select c.id, c.author, c.message, c.likes_count, c.created_at,
               exists (
                   select 1 from public.comment_likes cl
                   where cl.comment_id = c.id and cl.visitor_key = p_visitor_key
               )
        from public.comments c
        where c.photo_id = p_photo_id
        order by c.created_at, c.id;
    return;
end;
$$;

create or replace function public.like_photo(p_photo_id integer, p_visitor_key text)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    inserted_count integer;
    current_count integer;
begin
    if char_length(p_visitor_key) <> 64 then
        raise exception 'invalid visitor key' using errcode = '22023';
    end if;
    if not exists (select 1 from public.photos where id = p_photo_id) then
        raise exception 'photo not found' using errcode = 'P0002';
    end if;
    insert into public.photo_likes (photo_id, visitor_key)
    values (p_photo_id, p_visitor_key)
    on conflict do nothing;
    get diagnostics inserted_count = row_count;
    if inserted_count > 0 then
        update public.photos set likes_count = likes_count + 1 where id = p_photo_id;
        insert into public.usage_minutes (bucket_start, photo_like_count)
        values (date_trunc('minute', now()), 1)
        on conflict (bucket_start) do update set
            photo_like_count = public.usage_minutes.photo_like_count + 1;
    end if;
    select likes_count into current_count from public.photos where id = p_photo_id;
    return jsonb_build_object('likes', current_count, 'liked', true);
end;
$$;

