create table if not exists public.photos (
    id integer generated by default as identity primary key,
    title text not null check (char_length(title) <= 255),
    image_url text not null check (char_length(image_url) <= 500),
    likes_count integer not null default 0 check (likes_count >= 0),
    created_at timestamptz not null default now()
);

create table if not exists public.comments (
    id integer generated by default as identity primary key,
    photo_id integer not null references public.photos(id) on delete cascade,
    author text not null check (char_length(author) between 1 and 100),
    message text not null check (char_length(message) between 1 and 2000),
    likes_count integer not null default 0 check (likes_count >= 0),
    created_at timestamptz not null default now()
);

create index if not exists comments_photo_id_created_at_idx
    on public.comments (photo_id, created_at, id);

create table if not exists public.photo_likes (
    photo_id integer not null references public.photos(id) on delete cascade,
    visitor_key text not null check (char_length(visitor_key) = 64),
    created_at timestamptz not null default now(),
    primary key (photo_id, visitor_key)
);

create table if not exists public.comment_likes (
    comment_id integer not null references public.comments(id) on delete cascade,
    visitor_key text not null check (char_length(visitor_key) = 64),
    created_at timestamptz not null default now(),
    primary key (comment_id, visitor_key)
);

create table if not exists public.admin_access (
    user_id uuid primary key references auth.users(id) on delete cascade,
    username text not null unique check (username in ('g95rr', 'drsura.dev', 'admin2.dev', 'admin3.dev')),
    role text not null check (role in ('owner', 'admin')),
    enabled boolean not null default true,
    can_load_test boolean not null default false,
    created_at timestamptz not null default now(),
    constraint owner_load_permission check (role <> 'owner' or can_load_test)
);

create unique index if not exists admin_access_one_enabled_owner_idx
    on public.admin_access (role)
    where role = 'owner' and enabled;

create table if not exists public.usage_minutes (
    bucket_start timestamptz primary key,
    request_count integer not null default 0 check (request_count >= 0),
    error_count integer not null default 0 check (error_count >= 0),
    total_latency_ms bigint not null default 0 check (total_latency_ms >= 0),
    comment_count integer not null default 0 check (comment_count >= 0),
    photo_like_count integer not null default 0 check (photo_like_count >= 0),
    comment_like_count integer not null default 0 check (comment_like_count >= 0)
);

create table if not exists public.request_rate_limits (
    visitor_key text not null,
    action text not null,
    window_start timestamptz not null,
    request_count integer not null default 0,
    primary key (visitor_key, action, window_start)
);

create index if not exists request_rate_limits_window_start_idx
    on public.request_rate_limits (window_start);

create table if not exists public.demo_load_runs (
    id bigint generated by default as identity primary key,
    actor_username text not null,
    started_at timestamptz not null default now(),
    finished_at timestamptz not null,
    duration_ms integer not null check (duration_ms = 90000),
    simulated_vus integer not null check (simulated_vus = 10),
    result text not null check (result = 'simulated; no external load generated')
);

create index if not exists demo_load_runs_started_at_idx
    on public.demo_load_runs (started_at desc);

